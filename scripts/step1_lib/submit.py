"""Emit a shell file of sbatch commands for identify + cctyper per staged genome.

step1.md §8: MAG / phage / plasmid / unknown → prodigal meta; isolate → single.
"""
from __future__ import annotations

import csv
import stat
from pathlib import Path

from . import stage as stage_mod


def prodigal_mode(source_type: str) -> str:
    if source_type.strip().lower() == "isolate":
        return "single"
    return "meta"


def build_submit_script(manifest_rows: list[dict], staged_dir: Path,
                        raw_identify_dir: Path, raw_cctyper_dir: Path,
                        code_root: Path, out_path: Path,
                        skip_existing: bool) -> dict:
    identify_wrapper = code_root / "scripts/sbatch/identify_one.sh"
    cctyper_wrapper = code_root / "scripts/sbatch/cctyper_one.sh"

    lines = [
        "#!/bin/bash",
        "# Auto-generated by scripts/step1.py submit — DO NOT EDIT.",
        "# Run from a Rubin login node where sbatch is reachable.",
        "set -euo pipefail",
        "",
        f"IDENTIFY={identify_wrapper}",
        f"CCTYPER={cctyper_wrapper}",
        "",
    ]

    counts = {"identify": 0, "cctyper": 0,
              "skip_identify": 0, "skip_cctyper": 0,
              "staged_missing": 0}

    for row in manifest_rows:
        gid = row["genome_id"]
        guid = stage_mod.sanitize(gid)
        staged = staged_dir / f"{guid}.fna"
        if not staged.is_file():
            lines.append(f"# SKIP {gid}: staged FASTA missing ({staged})")
            counts["staged_missing"] += 1
            continue
        mode = prodigal_mode(row.get("source_type", "unknown"))

        id_out = raw_identify_dir / guid
        cc_out = raw_cctyper_dir / guid
        lines.append(f"# {gid}  source_type={row.get('source_type','?')}  prodigal={mode}")

        if skip_existing and id_out.is_dir():
            lines.append(f"# identify already present: {id_out}")
            counts["skip_identify"] += 1
        else:
            lines.append(f'sbatch --parsable "$IDENTIFY" "{guid}"')
            counts["identify"] += 1

        if skip_existing and cc_out.is_dir():
            lines.append(f"# cctyper already present: {cc_out}")
            counts["skip_cctyper"] += 1
        else:
            lines.append(f'sbatch --parsable "$CCTYPER" "{guid}" "{mode}"')
            counts["cctyper"] += 1

        lines.append("")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n")
    out_path.chmod(out_path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP)
    return {"submit_script": str(out_path), **counts}


def read_manifest(path: Path) -> list[dict]:
    with path.open(newline="") as fh:
        return list(csv.DictReader(fh, delimiter="\t"))
